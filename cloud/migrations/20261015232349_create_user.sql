CREATE COLLATION case_insensitive (
    PROVIDER = icu,
    LOCALE = 'en-US-u-ks-level2',
    DETERMINISTIC = FALSE
    );


CREATE TABLE "Users"
(
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT,
    email      TEXT COLLATE case_insensitive UNIQUE,
    updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ
);


CREATE TYPE "PublicKeyType" AS ENUM ('OnDevice', 'HardwareKey', 'SyncAble');

CREATE TABLE "UserPublicKeys"
(
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT,
    "type"     "PublicKeyType" NOT NULL,
    user_id    INT             NOT NULL,
    cred_id    TEXT UNIQUE,
    value      TEXT,
    created_at TIMESTAMPTZ,

    CONSTRAINT fk_user
        FOREIGN KEY (user_id)
            REFERENCES "Users" (id)
            ON DELETE CASCADE
);

CREATE TYPE "ChallengeKind" AS ENUM ('User', 'PublicKey');

CREATE UNLOGGED TABLE "PendingChallenge"
(
    owner        TEXT,
    kind         "ChallengeKind",
    value        TEXT,
    generated_on TIMESTAMPTZ,

    PRIMARY KEY (owner, kind)
);