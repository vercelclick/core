CREATE TABLE "Users"
(
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id UUID UNIQUE,
    name        TEXT,
    email       TEXT UNIQUE,
    updated_at  TIMESTAMPTZ DEFAULT NOW(),
    created_at  TIMESTAMPTZ DEFAULT NOW()
);


CREATE TYPE "PasskeyType" AS ENUM ('Local', 'Cloud');

CREATE TABLE "UserPasskeys"
(
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cred_id    TEXT UNIQUE,
    user_id    INT NOT NULL,
    name       TEXT,
    "type"     "PasskeyType",
    public_key TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT fk_passkey_user
        FOREIGN KEY (user_id)
            REFERENCES "Users" (id)
            ON DELETE CASCADE
);

CREATE TYPE "ChallengeKind" AS ENUM ('EmailSignup', 'EmailSignIn', 'PasskeySignup', 'PasskeySignIn', 'PasskeyAuthorize');

-- If a challenge is lost, the user can simply create a new one
CREATE UNLOGGED TABLE "PendingChallenge"
(
    owner         TEXT,
    kind          "ChallengeKind",
    value_hash    TEXT,
    generated_on  TIMESTAMPTZ DEFAULT NOW(),
    attempts_left INT NOT NULL,

    PRIMARY KEY (owner, kind)
);

-- If a session is lost, the user can simply create a new one
CREATE UNLOGGED TABLE "UserSessions"
(
    id           UUID PRIMARY KEY DEFAULT uuidv7(),
    user_id      INT NOT NULL,
    session_data JSONB,
    last_seen    TIMESTAMPTZ      DEFAULT NOW(),
    created_on   TIMESTAMPTZ      DEFAULT NOW(),
    expires_on   TIMESTAMPTZ      DEFAULT (NOW() + INTERVAL '7 days'),

    CONSTRAINT fk_session_user
        FOREIGN KEY (user_id)
            REFERENCES "Users" (id)
            ON DELETE CASCADE
)